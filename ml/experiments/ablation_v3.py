"""Stage-2 dev-fold ablation (v2 → v3): python -m ml.experiments.ablation_v3

Starts from the v2 setup (`ml/configs/short_gbm.yaml`) and tries the new data — point-in-time SEC fundamentals
and industry groups (SEC SIC codes) — on the 2016–2018 DEV folds only, greedily, keeping a group if it raises
the dev mean daily rank IC. The portfolio rule is not re-tuned (fewer choices made after seeing test results).
Writes docs/ABLATION_DEV_V3.md and prints the chosen feature spec.
"""

from __future__ import annotations

import argparse
import json
import logging
import time
from pathlib import Path
from typing import Any

import pandas as pd
import yaml

from ml.datasets.walkforward import yearly_folds
from ml.experiments.ablation import DEV_YEARS, _md
from ml.train import REPO, build_dataset, evaluate, load_lake, resolve_features, walk_forward

log = logging.getLogger("ml.ablation_v3")


def main(argv: list[str] | None = None) -> int:
    logging.basicConfig(level=logging.INFO, format="%(asctime)s %(levelname)s %(message)s")
    ap = argparse.ArgumentParser(prog="python -m ml.experiments.ablation_v3")
    ap.add_argument("--config", default="ml/configs/short_gbm.yaml")
    ap.add_argument("--out", type=Path, default=REPO / "docs" / "ABLATION_DEV_V3.md")
    a = ap.parse_args(argv)
    cfg = yaml.safe_load(Path(a.config).read_text())
    h, label = int(cfg["horizon"]), f"{cfg['target']}_{cfg['horizon']}"
    t0 = time.time()

    lake = load_lake(cfg)
    lake.prices = lake.prices[pd.to_datetime(lake.prices["date"]) <= pd.Timestamp(f"{DEV_YEARS[-1]}-12-31")]
    df = build_dataset(lake, h, cfg["data"]["min_history_days"])
    folds = list(yearly_folds(df["date"], DEV_YEARS, h, int(cfg["validation"]["embargo_days"])))
    rows: list[dict[str, Any]] = []

    def trial(step: str, spec: dict[str, Any], ens: bool = False) -> dict[str, float]:
        feats = resolve_features(spec)
        models = {k: cfg["models"][k] for k in (("lightgbm", "xgboost") if ens else ("lightgbm",))}
        oos, _ = walk_forward(df, feats, label, h, models, folds, list(models) if ens else None)
        m = evaluate(oos["ensemble" if ens else "lightgbm"], label, h, cfg["backtest"])
        rows.append({"step": step, "model": "ensemble" if ens else "lightgbm", "n_features": len(feats), **m})
        log.info("%-40s IC %.4f (t %.2f)", step, m["ic_mean"], m["ic_tstat"])
        return m

    spec: dict[str, Any] = json.loads(json.dumps(cfg["features"]))
    best = trial("v2 features (reference)", spec)
    for group in ("fundamentals", "industry"):
        cand = {**spec, "add": [*spec["add"], group]}
        m = trial(f"+ {group}", cand)
        if m["ic_mean"] > best["ic_mean"]:
            spec, best = cand, m
    ref_ens = trial("v2 ensemble (reference)", json.loads(json.dumps(cfg["features"])), ens=True)
    new_ens = trial("chosen features · ensemble", spec, ens=True) if spec != cfg["features"] else ref_ens
    chosen = {
        "features": spec,
        "dev_ic_v2_ensemble": ref_ens["ic_mean"],
        "dev_ic_v3_ensemble": new_ens["ic_mean"],
    }

    r = pd.DataFrame(rows)
    cols = [
        "step",
        "model",
        "n_features",
        "ic_mean",
        "ic_tstat",
        "auc",
        "auc_rel",
        "hit_rate",
        "strat_sharpe",
        "bench_sharpe",
        "turnover_2sided",
    ]
    a.out.write_text(
        "\n".join(
            [
                "# Dev-fold ablation, stage 2 (v2 → v3): new data",
                "",
                f"Generated by `python -m ml.experiments.ablation_v3` ({round(time.time() - t0)} s, CPU). Dev folds "
                f"{DEV_YEARS}; label `{label}`; portfolio rule of v2 unchanged. New groups: point-in-time SEC "
                "fundamentals (10 within-day ranks) and industry-relative returns (SEC SIC → 9 groups). A group is "
                "kept only if it raises dev IC.",
                "",
                _md(r[cols], 4),
                "",
                "```json",
                json.dumps(chosen, indent=2),
                "```",
                "",
            ]
        )
    )
    print(json.dumps(chosen, indent=2))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
