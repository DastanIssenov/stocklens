"""Data-quality report → docs/DATA_REPORT.md (coverage, gaps, flags, cross-checks, KZ liquidity)."""

from __future__ import annotations

import datetime as dt

import pandas as pd

from data_pipeline import cleaning, storage
from data_pipeline.config import REPORT_PATH


def _md(df: pd.DataFrame, floatfmt: str = "{:.4g}") -> str:
    if df.empty:
        return "_(empty)_\n"
    cols = list(df.columns)
    lines = ["| " + " | ".join(cols) + " |", "|" + "---|" * len(cols)]
    for _, r in df.iterrows():
        cells = []
        for c in cols:
            v = r[c]
            cells.append(floatfmt.format(v) if isinstance(v, float) else str(v))
        lines.append("| " + " | ".join(cells) + " |")
    return "\n".join(lines) + "\n"


def coverage(prices: pd.DataFrame) -> pd.DataFrame:
    if prices.empty:
        return pd.DataFrame()
    g = prices.groupby("symbol")
    out = pd.DataFrame(
        {
            "first": g["date"].min(),
            "last": g["date"].max(),
            "rows": g.size(),
            "zero_vol": g["flag_zero_volume"].sum() if "flag_zero_volume" in prices else 0,
            "jumps": g["flag_jump"].sum() if "flag_jump" in prices else 0,
        }
    ).reset_index()
    span_days = (pd.to_datetime(out["last"]) - pd.to_datetime(out["first"])).dt.days.clip(lower=1)
    out["rows_per_year"] = (out["rows"] / (span_days / 365.25)).round(0)
    return out


def calendar_gaps(prices: pd.DataFrame, min_gap_days: int = 6) -> pd.DataFrame:
    """Calendar gaps longer than `min_gap_days` (holidays are ≤ 4 days; longer = missing data or halts)."""
    rows = []
    for sym, g in prices.sort_values("date").groupby("symbol"):
        d = pd.to_datetime(g["date"])
        gaps = d.diff().dt.days
        for i in gaps[gaps > min_gap_days].index:
            rows.append(
                {"symbol": sym, "from": d.shift(1)[i].date(), "to": d[i].date(), "days": int(gaps[i])}
            )
    return pd.DataFrame(rows)


def build_report() -> str:
    us, kz = storage.read("prices_us"), storage.read("prices_kz")
    uni, acts = storage.read("universe_us"), storage.read("corporate_actions_us")
    macro, fx, mkt, fund = (
        storage.read(n) for n in ("macro_fred", "fx_nbk", "market_yahoo", "fundamentals_us")
    )
    parts = [
        "# Data quality report\n",
        f"Generated by `python -m data_pipeline report` on {dt.date.today().isoformat()}. "
        "Lake: `data/lake/*.parquet` (git-ignored). Rules: docs/GPU_PLAN.md §2.3–2.5.\n",
        "## Datasets\n",
        _md(
            pd.DataFrame(
                [
                    {"dataset": "universe_us", "rows": len(uni)},
                    {"dataset": "prices_us", "rows": len(us)},
                    {"dataset": "corporate_actions_us", "rows": len(acts)},
                    {"dataset": "prices_kz", "rows": len(kz)},
                    {"dataset": "market_yahoo", "rows": len(mkt)},
                    {"dataset": "macro_fred", "rows": len(macro)},
                    {"dataset": "fx_nbk", "rows": len(fx)},
                    {"dataset": "fundamentals_us", "rows": len(fund)},
                ]
            )
        ),
    ]
    if not us.empty:
        cov = coverage(us)
        parts += [
            "## US prices\n",
            f"- {cov['symbol'].nunique()} symbols, {len(us):,} bars, {us['date'].min()} → {us['date'].max()}; "
            f"sources: {', '.join(f'{k} {v:,}' for k, v in us['source'].value_counts().items())}.\n",
            f"- Symbols with < 10 years of history: {int((pd.to_datetime(cov['first']) > pd.Timestamp('2016-11-01')).sum())} "
            "(listed later — e.g. recent IPOs/spin-offs).\n",
            f"- Bars flagged as > 50 % one-day jumps (need corporate-action check): {int(cov['jumps'].sum())}.\n",
        ]
        jumps = us[us.get("flag_jump", False) == True]  # noqa: E712
        if not jumps.empty:
            j = jumps[["symbol", "date", "close", "source"]].head(15)
            if not acts.empty:
                splits = acts[acts["type"].str.contains("split")][["symbol", "date"]].assign(
                    split_on_day=True
                )
                j = j.merge(splits, on=["symbol", "date"], how="left").fillna({"split_on_day": False})
            parts += ["Flagged jumps (raw prices, first 15):\n", _md(j)]
        gaps = calendar_gaps(us)
        parts += [f"- Calendar gaps > 6 days: {len(gaps)}.\n", _md(gaps.head(15)) if len(gaps) else ""]
        adj_missing = us["adj_close"].isna().mean() if "adj_close" in us else 1.0
        parts.append(f"- Share of bars without `adj_close`: {adj_missing:.2%}.\n")
        if not mkt.empty and "SPY" in set(mkt["symbol"]):
            pass
        y_overlap = us[us["source"] == "yahoo"]
        if not y_overlap.empty:
            parts.append(
                f"- Pre-2016 history from Yahoo: {y_overlap['symbol'].nunique()} symbols, {len(y_overlap):,} bars.\n"
            )
    if not kz.empty:
        cov = coverage(kz)
        liq = cleaning.illiquidity(kz)
        parts += [
            "## Kazakhstan prices (KASE via Tradernet, LSE GDRs via Yahoo)\n",
            _md(cov.merge(liq, on="symbol", how="left")),
            "`rows_per_year` well below 250 = days without trades (normal for thin KASE names in early years). "
            "`zero_volume_share`/`amihud` are over the last 63 rows.\n",
        ]
    if not macro.empty:
        m = (
            macro.groupby(["series_id", "name"])
            .agg(
                first=("date", "min"),
                last=("date", "max"),
                rows=("date", "size"),
                median_lag_days=("available_at", lambda s: None),
            )
            .reset_index()
        )
        lag = macro.assign(
            lag=(pd.to_datetime(macro["available_at"]) - pd.to_datetime(macro["date"])).dt.days
        )
        m["median_lag_days"] = m["series_id"].map(lag.groupby("series_id")["lag"].median())
        parts += [
            "## Macro (FRED, first-release vintages)\n",
            _md(m),
            "`median_lag_days` = typical delay between the observation date and its first publication — "
            "features must use `available_at`, not `date`.\n",
        ]
    if not fx.empty:
        parts.append(
            f"## USD/KZT official (NBK)\n- {len(fx)} days, {fx['date'].min()} → {fx['date'].max()}, "
            f"range {fx['usdkzt'].min():.2f}–{fx['usdkzt'].max():.2f}.\n"
        )
    if not fund.empty:
        lagd = (
            pd.to_datetime(fund["available_at"], utc=True).dt.tz_localize(None)
            - pd.to_datetime(fund["period_end"])
        ).dt.days
        parts += [
            "## US fundamentals (SEC companyfacts)\n",
            f"- {fund['symbol'].nunique()} companies, {len(fund):,} facts, metrics: "
            f"{', '.join(sorted(fund['metric'].unique()))}.\n",
            f"- Median delay period end → publication: {lagd.median():.0f} days "
            "(this is why `period_end` must never be used as the feature date).\n",
        ]
    parts += [
        "## Known limitations\n",
        "- **Survivorship bias:** the US universe is today's 100 most liquid operating companies "
        "(built from Alpaca + SEC). Point-in-time membership is planned (GPU_PLAN §2.1 #2); "
        "until then backtest numbers are optimistic.\n",
        "- KASE: no dividend-adjusted series (`adj_close` empty); dividends must be added from KASE notices.\n",
        "- News history is not in the lake yet (≈ 7 h download, GPU_PLAN §2.2).\n",
    ]
    text = "\n".join(p for p in parts if p)
    REPORT_PATH.write_text(text)
    return text
